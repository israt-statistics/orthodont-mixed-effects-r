library(nlme)
library(ggplot2)
ortho <- as.data.frame(Orthodont) 
str(ortho)
summary(ortho)
p1 <- ggplot(ortho, aes(x = age, y = distance, group = Subject, colour = Sex)) +geom_line(alpha = 0.5) +stat_smooth(aes(group = Sex), method = "lm", se = FALSE, linewidth = 1.3) +labs(x = "Age (years)", y = "Distance (mm)",title = "Individual growth trajectories by sex") +theme_minimal()
p1
m1 <- lme(distance ~ age, random = ~ 1 | Subject, data = ortho)
m2 <- lme(distance ~ age, random = ~ age | Subject, data = ortho)
summary(m1)
summary(m2)
anova(m1, m2)
m_noSex <- lme(distance ~ age,       random = ~ age | Subject, data = ortho, method = "ML")
m_sex   <- lme(distance ~ age + Sex, random = ~ age | Subject, data = ortho, method = "ML")
m_int   <- lme(distance ~ age * Sex, random = ~ age | Subject, data = ortho, method = "ML")
anova(m_noSex, m_sex, m_int)
m_final <- lme(distance ~ age * Sex, random = ~ age | Subject, data = ortho)
summary(m_final)
intervals(m_final, which = "fixed")
vc  <- as.numeric(VarCorr(m1)[, "Variance"])
icc <- vc[1] / sum(vc)
icc
ortho$fitted_val <- fitted(m_final)
ortho$resid_val  <- resid(m_final, type = "normalized")
p2 <- ggplot(ortho, aes(fitted_val, resid_val)) +geom_point(alpha = 0.6) +geom_hline(yintercept = 0, linetype = "dashed") +labs(x = "Fitted values", y = "Normalized residuals",title = "Residuals vs fitted") +theme_minimal()
p2
qqnorm(ortho$resid_val, main = "Normal Q-Q: residuals")
qqline(ortho$resid_val)
re <- ranef(m_final)
qqnorm(re[, 1], main = "Normal Q-Q: random intercepts"); qqline(re[, 1])
newdat <- expand.grid(age = seq(8, 14, 0.5), Sex = c("Male", "Female"))
newdat$pred <- predict(m_final, newdat, level = 0)
p3 <- ggplot() +geom_line(data = ortho, aes(age, distance, group = Subject, colour = Sex), alpha = 0.25) +geom_line(data = newdat, aes(age, pred, colour = Sex), linewidth = 1.5) +labs(x = "Age (years)", y = "Distance (mm)",title = "Model-predicted average growth by sex") +theme_minimal()
